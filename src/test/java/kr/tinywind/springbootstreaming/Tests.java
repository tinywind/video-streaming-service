    @Test
    public void preservesImportedIdentityIdsWhenAddingAnnotations() throws Exception {
        Path database = Files.createTempDirectory(Paths.get(System.getProperty("java.io.tmpdir")), "video-import-").resolve("annotations");
        String url = "jdbc:h2:file:" + database.toAbsolutePath() + ";NON_KEYWORDS=KEY";
        try (Connection connection = DriverManager.getConnection(url, "sa", ""); Statement sql = connection.createStatement()) {
            sql.execute("create table material (id bigint generated by default as identity (start with 2) primary key, created_at timestamp not null, video_name varchar(1024) not null)");
            sql.execute("create table material_data (id bigint generated by default as identity (start with 2) primary key, key varchar(255) not null, timestamp double precision not null, material_id bigint not null references material(id))");
            sql.execute("insert into material values (1, timestamp '2016-06-01 12:00:00', '/video-random-accessible/imported.mp4')");
            sql.execute("insert into material_data values (1, '=1+1', 1.25, 1)");
            try (ConfigurableApplicationContext imported = SpringApplication.run(Launcher.class,
                    "--server.port=0", "--server.address=127.0.0.1", "--spring.datasource.url=" + url,
                    "--spring.jpa.hibernate.ddl-auto=update")) {
                MaterialRepository repository = imported.getBean(MaterialRepository.class);
                Material existing = repository.findById(1L).get();
                assertEquals("/video-random-accessible/imported.mp4", existing.getVideoName());
                assertEquals(1, existing.getMaterialDataList().size());
                assertEquals("=1+1", existing.getMaterialDataList().get(0).getKey());
                String importedBase = "http://127.0.0.1:" + imported.getEnvironment().getProperty("local.server.port");
                try (Response response = new Response((HttpURLConnection) new URL(importedBase + "/download-csv/1").openConnection())) {
                    assertEquals(200, response.status);
                    assertTrue(response.text().contains("1.25,'=1+1"));
                }
                Material added = new Material("/video-random-accessible/new.mp4");
                added.getMaterialDataList().add(new MaterialData(null, 2.5, "w"));
                repository.saveAndFlush(added);
                assertTrue(added.getId() > existing.getId());
                assertTrue(added.getMaterialDataList().get(0).getId() > existing.getMaterialDataList().get(0).getId());
                assertEquals(2, repository.count());
                assertEquals("=1+1", repository.findById(1L).get().getMaterialDataList().get(0).getKey());
            } finally {
                sql.execute("drop all objects");
            }
        }
    }

    @Test
    public void exportsFormulaKeysAsTextWithoutChangingStoredAnnotations() throws Exception {
        String[][] samples = {{"q", "q"}, {"w", "w"}, {"e", "e"}, {"a", "a"}, {"s", "s"},
                {"d", "d"}, {"z", "z"}, {"x", "x"}, {"c", "c"}, {"custom-key", "custom-key"},
                {"custom, \"quoted\"\nsecond line", "custom, \"quoted\"\nsecond line"},
                {"=1+1", "'=1+1"}, {"+1", "'+1"}, {"-1", "'-1"}, {"@SUM(A1)", "'@SUM(A1)"},
                {"  =1+1", "'  =1+1"}, {"\ttext", "'\ttext"}, {" \r\n=1+1", "' \r\n=1+1"}};
        MaterialRepository repository = application.getBean(MaterialRepository.class);
        Material material = new Material("/video-random-accessible/custom.mp4");
        for (int i = 0; i < samples.length; i++) material.getMaterialDataList().add(new MaterialData(null, (double) i, samples[i][0]));
        repository.saveAndFlush(material);
        try (Response response = get("/download-csv/" + material.getId(), null)) {
            assertEquals(200, response.status);
            String csv = response.text();
            assertTrue(csv.contains("\"' \r\n=1+1\""));
            for (int i = 0; i < 9; i++) assertTrue(csv.contains(i + ".0," + samples[i][0] + "\r\n"));
            try (ICsvListReader reader = new CsvListReader(new StringReader(csv), CsvPreference.STANDARD_PREFERENCE)) {
                assertArrayEquals(new String[]{"timestamp", "key"}, reader.getHeader(true));
                List<String> row;
                int count = 0;
                while ((row = reader.read()) != null) {
                    int index = (int) Double.parseDouble(row.get(0));
                    assertEquals(samples[index][1].replace("\r\n", "\n"), row.get(1));
                    count++;
                }
                assertEquals(samples.length, count);
            }
            Material unchanged = repository.findById(material.getId()).get();
            for (MaterialData data : unchanged.getMaterialDataList()) assertEquals(samples[data.getTimestamp().intValue()][0], data.getKey());
        } finally {
            repository.delete(material);
            repository.flush();
        }
    }

